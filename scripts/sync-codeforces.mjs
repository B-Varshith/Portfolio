/**
 * Regenerates `data/codeforces.ts` straight from the public Codeforces API.
 *
 *   node scripts/sync-codeforces.mjs
 *
 * No auth, no keys — only public endpoints. Run it whenever the profile moves.
 */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HANDLE = "bvarshith_77";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

async function cf(method, params = "") {
  const res = await fetch(`https://codeforces.com/api/${method}?${params}`);
  if (!res.ok) throw new Error(`${method} -> HTTP ${res.status}`);
  const json = await res.json();
  if (json.status !== "OK") throw new Error(`${method} -> ${json.comment ?? "error"}`);
  return json.result;
}

const iso = (seconds) => new Date(seconds * 1000).toISOString().slice(0, 10);

const [info, history, submissions] = await Promise.all([
  cf("user.info", `handles=${HANDLE}`),
  cf("user.rating", `handle=${HANDLE}`),
  cf("user.status", `handle=${HANDLE}&from=1&count=100000`),
]);

const me = info[0];

const solved = new Map();
const verdicts = {};
const languages = {};
const tagCounts = {};

for (const s of submissions) {
  verdicts[s.verdict] = (verdicts[s.verdict] ?? 0) + 1;
  languages[s.programmingLanguage] = (languages[s.programmingLanguage] ?? 0) + 1;
  if (s.verdict !== "OK") continue;
  const key = `${s.problem.contestId}-${s.problem.index}`;
  if (solved.has(key)) continue;
  solved.set(key, true);
  for (const tag of s.problem.tags ?? []) tagCounts[tag] = (tagCounts[tag] ?? 0) + 1;
}

const topTags = Object.entries(tagCounts)
  .sort((a, b) => b[1] - a[1])
  .slice(0, 12)
  .map(([tag, count]) => ({ tag, count }));

const contests = history.map((h) => ({
  date: iso(h.ratingUpdateTimeSeconds),
  name: h.contestName,
  rank: h.rank,
  from: h.oldRating,
  to: h.newRating,
}));

const ranks = contests.map((c) => c.rank);
const bestRank = Math.min(...ranks);

const out = `/**
 * AUTO-GENERATED by scripts/sync-codeforces.mjs — do not edit by hand.
 * Source: public Codeforces API (user.info, user.rating, user.status).
 * Generated: ${new Date().toISOString().slice(0, 10)}
 */

export interface CfContest {
  date: string;
  name: string;
  rank: number;
  from: number;
  to: number;
}

export const cfHandle = ${JSON.stringify(me.handle)};
export const cfProfileUrl = ${JSON.stringify(`https://codeforces.com/profile/${me.handle}`)};

export const cfRating = ${me.rating};
export const cfMaxRating = ${me.maxRating};
export const cfRank = ${JSON.stringify(me.rank)};
export const cfMaxRank = ${JSON.stringify(me.maxRank)};
export const cfRegistered = ${JSON.stringify(iso(me.registrationTimeSeconds))};

export const cfStats = {
  contests: ${contests.length},
  problemsSolved: ${solved.size},
  submissions: ${submissions.length},
  accepted: ${verdicts.OK ?? 0},
  bestRank: ${bestRank},
  languages: ${JSON.stringify(languages, null, 2)},
  verdicts: ${JSON.stringify(verdicts, null, 2)},
  topTags: ${JSON.stringify(topTags, null, 2)},
} as const;

export const cfContests: CfContest[] = ${JSON.stringify(contests, null, 2)};
`;

await writeFile(join(root, "data", "codeforces.ts"), out, "utf8");

console.log(
  `wrote data/codeforces.ts — rating ${me.rating}, ${contests.length} contests, ${solved.size} solved, best rank #${bestRank}`,
);
